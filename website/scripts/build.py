import hashlib
def _ver():
    h = hashlib.md5()
    for f in ('css/design-system.css', 'js/site.js', 'js/fx.js', 'js/scenes.js', 'js/scenario.js', 'js/overview.js', 'js/charts.js', 'js/tools-math.js', 'js/config.js', 'js/markets.js', 'js/locales.js'):
        try: h.update(open(os.path.join(ROOT, f), 'rb').read())
        except OSError: pass
    return h.hexdigest()[:8]
VER = _ver()
used_keys = set()
def esc(t): return html.escape(t, quote=True)
def hu(key, **vars):
    t = S[key][0]
    for k, v in vars.items(): t = t.replace('{%s}' % k, str(v))
    return t
def tx(key, tag='span', cls='', vars=None, extra=''):
    used_keys.add(key)
    v = ' data-i18n-vars=\'%s\'' % json.dumps(vars) if vars else ''
    c = ' class="%s"' % cls if cls else ''
    return '<%s%s data-i18n="%s"%s%s>%s</%s>' % (tag, c, key, v, (' ' + extra) if extra else '', esc(hu(key, **(vars or {}))), tag)
def attrs(**kw):
    out = []; pairs = []
    for a, k in kw.items():
        a = a.replace('_', '-'); used_keys.add(k); out.append('%s="%s"' % (a, esc(hu(k)))); pairs.append('%s:%s' % (a, k))
    return ' '.join(out) + ' data-i18n-attr="%s"' % ';'.join(pairs)

