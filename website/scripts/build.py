# ---------------------------------------------------------------- i18n validation + locales.js
def placeholders(t): return sorted(re.findall(r'\{(\w+)\}', t))
errors = []
for k, v in S.items():
    if len(v) != 3 or any(not x.strip() for x in v): errors.append('missing translation: ' + k)
    elif not (placeholders(v[0]) == placeholders(v[1]) == placeholders(v[2])): errors.append('placeholder mismatch: ' + k)
if errors: sys.exit('\n'.join(errors))
locales = {l: {k: v[i] for k, v in S.items()} for i, l in enumerate(LANGS)}
